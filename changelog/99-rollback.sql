ALTER PROCEDURE INT_SD_1_TK_DN (P_COMPANY DM_ID,
P_ACCOUNT DM_ID,
P_NGAY DM_DATE)
RETURNS (AMOUNT DM_DOUBLE,
DEBIT DM_DOUBLE,
CREDIT DM_DOUBLE)
AS 
DECLARE VARIABLE PERIOD DM_ID;
DECLARE VARIABLE BEGINNING_DATE DM_DATE;
DECLARE VARIABLE BEGINNING_AMOUNT DM_DOUBLE;
DECLARE VARIABLE BEGINNING_DEBIT DM_DOUBLE;
DECLARE VARIABLE BEGINNING_CREDIT DM_DOUBLE;
DECLARE VARIABLE RISING_DEBIT_AMOUNT DM_DOUBLE;
DECLARE VARIABLE RISING_DEBIT DM_DOUBLE;
DECLARE VARIABLE RISING_CREDIT_AMOUNT DM_DOUBLE;
DECLARE VARIABLE RISING_CREDIT DM_DOUBLE;
BEGIN
    SELECT ID, BEGINNING_DATE
    FROM CMD_GET_PERIOD_FROM_DATE(:P_COMPANY, :P_NGAY)
    INTO :PERIOD, :BEGINNING_DATE;

    SELECT SUM(AMOUNT), SUM(OFFICIAL_DEBIT), SUM(OFFICIAL_CREDIT)
    FROM BALANCES
    WHERE BALANCES.COMPANY = :P_COMPANY AND PERIOD = :PERIOD AND ACCOUNT = :P_ACCOUNT
    INTO :BEGINNING_AMOUNT, :BEGINNING_DEBIT, :BEGINNING_CREDIT;

    IF(BEGINNING_AMOUNT IS NULL)THEN BEGINNING_AMOUNT = 0;
    IF(BEGINNING_DEBIT IS NULL)THEN BEGINNING_DEBIT = 0;
    IF(BEGINNING_CREDIT IS NULL)THEN BEGINNING_CREDIT = 0;

    IF(BEGINNING_DATE <> P_NGAY)THEN
    BEGIN
        SELECT DEBIT_AMOUNT, DEBIT, CREDIT_AMOUNT, CREDIT
        FROM INT_PS_1_TK(:P_COMPANY, :P_ACCOUNT, :BEGINNING_DATE, DATEADD(DAY, -1, :P_NGAY))
        INTO :RISING_DEBIT_AMOUNT, :RISING_DEBIT, :RISING_CREDIT_AMOUNT, :RISING_CREDIT;
    END

    IF(RISING_DEBIT_AMOUNT IS NULL)THEN RISING_DEBIT_AMOUNT = 0;
    IF(RISING_DEBIT IS NULL)THEN RISING_DEBIT = 0;
    IF(RISING_CREDIT_AMOUNT IS NULL)THEN RISING_CREDIT_AMOUNT = 0;
    IF(RISING_CREDIT IS NULL)THEN RISING_CREDIT = 0;

    AMOUNT = BEGINNING_AMOUNT + RISING_DEBIT_AMOUNT - RISING_CREDIT_AMOUNT;
    DEBIT = BEGINNING_DEBIT + RISING_DEBIT - BEGINNING_CREDIT - RISING_CREDIT;

    IF(DEBIT > 0)THEN
        CREDIT = 0;
    ELSE
    BEGIN
        CREDIT = ABS(DEBIT);
        DEBIT = 0;
    END

    SUSPEND;
END ^

ALTER PROCEDURE INT_SD_1_TK_DT0_DN (P_COMPANY DM_ID,
P_ACCOUNT DM_ID,
P_IS_GOODS_ACCOUNT DM_BOOL,
P_NGAY DM_DATE)
RETURNS (OBJECT0 DM_ID,
AMOUNT DM_DOUBLE,
DEBIT DM_DOUBLE,
CREDIT DM_DOUBLE)
AS 
DECLARE VARIABLE PERIOD DM_ID;
DECLARE VARIABLE BEGINNING_DATE DM_DATE;
BEGIN
    SELECT ID, BEGINNING_DATE
    FROM CMD_GET_PERIOD_FROM_DATE(:P_COMPANY, :P_NGAY)
    INTO :PERIOD, :BEGINNING_DATE;

    IF(BEGINNING_DATE = P_NGAY)THEN
    BEGIN
        FOR
            SELECT OBJECT0, SUM(AMOUNT), SUM(OFFICIAL_DEBIT), SUM(OFFICIAL_CREDIT)
            FROM BALANCES
            WHERE BALANCES.COMPANY = :P_COMPANY AND PERIOD = :PERIOD AND ACCOUNT = :P_ACCOUNT AND OBJECT0 IS NOT NULL
            GROUP BY OBJECT0
            INTO :OBJECT0, :AMOUNT, :DEBIT, :CREDIT
        DO
        BEGIN
            DEBIT = DEBIT - CREDIT;

            IF(DEBIT > 0)THEN
                CREDIT = 0;
            ELSE
            BEGIN
                CREDIT = ABS(DEBIT);
                DEBIT = 0;
            END

            IF(DEBIT <> 0 OR CREDIT <> 0 OR (P_IS_GOODS_ACCOUNT = 1 AND AMOUNT <> 0))THEN
                SUSPEND;
        END
    END
    ELSE
    BEGIN
        FOR
            SELECT OBJECT0, SUM(AMOUNT), SUM(DEBIT), SUM(CREDIT)
            FROM
            (
                SELECT OBJECT0, AMOUNT, OFFICIAL_DEBIT DEBIT, OFFICIAL_CREDIT CREDIT
                FROM BALANCES
                WHERE BALANCES.COMPANY = :P_COMPANY AND PERIOD = :PERIOD AND ACCOUNT = :P_ACCOUNT AND OBJECT0 IS NOT NULL

                UNION ALL

                SELECT OBJECT0, DEBIT_AMOUNT-CREDIT_AMOUNT AS AMOUNT, DEBIT, CREDIT
                FROM INT_PS_1_TK_DT0(:P_COMPANY, :P_ACCOUNT, :BEGINNING_DATE, DATEADD(DAY, -1, :P_NGAY))
            )
            GROUP BY OBJECT0
            INTO :OBJECT0, :AMOUNT, :DEBIT, :CREDIT
        DO
        BEGIN
            DEBIT = DEBIT - CREDIT;

            IF(DEBIT > 0)THEN
                CREDIT = 0;
            ELSE
            BEGIN
                CREDIT = ABS(DEBIT);
                DEBIT = 0;
            END

            IF(DEBIT <> 0 OR CREDIT <> 0 OR (P_IS_GOODS_ACCOUNT = 1 AND AMOUNT <> 0))THEN
                SUSPEND;
        END
    END
END ^

