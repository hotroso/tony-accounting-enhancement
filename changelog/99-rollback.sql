ALTER PROCEDURE INT_PS_1_TK (P_COMPANY DM_ID,
P_ACCOUNT DM_ID,
P_TU_NGAY DM_DATE,
P_DEN_NGAY DM_DATE)
RETURNS (DEBIT_AMOUNT DM_DOUBLE,
DEBIT DM_DOUBLE,
CREDIT_AMOUNT DM_DOUBLE,
CREDIT DM_DOUBLE)
AS 
BEGIN
    SELECT SUM(CREDIT_DEBIT.AMOUNT), SUM(CREDIT_DEBIT.OFFICIAL_SUM_OF_MONEY)
    FROM CREDIT_DEBIT
    WHERE CREDIT_DEBIT.COMPANY = :P_COMPANY AND
            CREDIT_DEBIT.SIDE = 0 AND
            CREDIT_DEBIT.ACCOUNT = :P_ACCOUNT AND
    EXISTS
    (
        SELECT ID
        FROM ENTRIES
        WHERE ENTRIES.COMPANY = :P_COMPANY AND CREDIT_DEBIT.ENTRY = ID AND
        EXISTS
            (
                SELECT ID
                FROM DOCUMENTS
                WHERE DOCUMENTS.COMPANY = :P_COMPANY AND ENTRIES.DOCUMENT = ID AND
                      DOCUMENTS.INPUT_DATE BETWEEN :P_TU_NGAY AND :P_DEN_NGAY
            )
    )
    INTO :DEBIT_AMOUNT, :DEBIT;

    SELECT SUM(CREDIT_DEBIT.AMOUNT), SUM(CREDIT_DEBIT.OFFICIAL_SUM_OF_MONEY)
    FROM CREDIT_DEBIT
    WHERE CREDIT_DEBIT.COMPANY = :P_COMPANY AND
        CREDIT_DEBIT.SIDE = 1 AND
        CREDIT_DEBIT.ACCOUNT = :P_ACCOUNT AND
    EXISTS
    (
        SELECT ID
        FROM ENTRIES
        WHERE ENTRIES.COMPANY = :P_COMPANY AND CREDIT_DEBIT.ENTRY = ID AND
        EXISTS
            (
                SELECT ID
                FROM DOCUMENTS
                WHERE DOCUMENTS.COMPANY = :P_COMPANY AND ENTRIES.DOCUMENT = ID AND
                      DOCUMENTS.INPUT_DATE BETWEEN :P_TU_NGAY AND :P_DEN_NGAY
            )
    )
    INTO :CREDIT_AMOUNT, :CREDIT;

    IF(DEBIT IS NULL)THEN DEBIT = 0;
    IF(DEBIT_AMOUNT IS NULL)THEN DEBIT_AMOUNT = 0;
    IF(CREDIT IS NULL)THEN CREDIT = 0;
    IF(CREDIT_AMOUNT IS NULL)THEN CREDIT_AMOUNT = 0;

    SUSPEND;
END ^

