SET TERM ^ ;

/* Ham tao index neu chua ton tai (theo ten, khong phan biet hoa/thuong) */
EXECUTE BLOCK AS
BEGIN
    /* ---- BALANCES ---- */
    IF (NOT EXISTS(SELECT 1 FROM RDB$INDICES WHERE RDB$INDEX_NAME = 'IDX_BAL_COMPANY_PERIOD')) THEN
        EXECUTE STATEMENT 'CREATE INDEX IDX_BAL_COMPANY_PERIOD ON BALANCES (COMPANY, PERIOD)';
    IF (NOT EXISTS(SELECT 1 FROM RDB$INDICES WHERE RDB$INDEX_NAME = 'IDX_BAL_PERIOD_ACC')) THEN
        EXECUTE STATEMENT 'CREATE INDEX IDX_BAL_PERIOD_ACC ON BALANCES (PERIOD, ACCOUNT)';
    IF (NOT EXISTS(SELECT 1 FROM RDB$INDICES WHERE RDB$INDEX_NAME = 'IDX_BAL_PERIOD_ACC_OBJ0')) THEN
        EXECUTE STATEMENT 'CREATE INDEX IDX_BAL_PERIOD_ACC_OBJ0 ON BALANCES (PERIOD, ACCOUNT, OBJECT0)';

    /* ---- CREDIT_DEBIT ---- */
    IF (NOT EXISTS(SELECT 1 FROM RDB$INDICES WHERE RDB$INDEX_NAME = 'IDX_CD_COMPANY_ACC_OBJ0')) THEN
        EXECUTE STATEMENT 'CREATE INDEX IDX_CD_COMPANY_ACC_OBJ0 ON CREDIT_DEBIT (COMPANY, ACCOUNT, OBJECT0)';
    IF (NOT EXISTS(SELECT 1 FROM RDB$INDICES WHERE RDB$INDEX_NAME = 'IDX_CD_COMPANY_ACC_SIDE')) THEN
        EXECUTE STATEMENT 'CREATE INDEX IDX_CD_COMPANY_ACC_SIDE ON CREDIT_DEBIT (COMPANY, ACCOUNT, SIDE)';
    IF (NOT EXISTS(SELECT 1 FROM RDB$INDICES WHERE RDB$INDEX_NAME = 'IDX_CD_ENTRY_ACC_OBJ0')) THEN
        EXECUTE STATEMENT 'CREATE INDEX IDX_CD_ENTRY_ACC_OBJ0 ON CREDIT_DEBIT (ENTRY, ACCOUNT, OBJECT0)';
    IF (NOT EXISTS(SELECT 1 FROM RDB$INDICES WHERE RDB$INDEX_NAME = 'IDX_CD_ENTRY_ACC_SIDE')) THEN
        EXECUTE STATEMENT 'CREATE INDEX IDX_CD_ENTRY_ACC_SIDE ON CREDIT_DEBIT (ENTRY, ACCOUNT, SIDE)';

    /* ---- DOCUMENTS ---- */
    IF (NOT EXISTS(SELECT 1 FROM RDB$INDICES WHERE RDB$INDEX_NAME = 'DOCUMENTS_COMPANY_IDX')) THEN
        EXECUTE STATEMENT 'CREATE INDEX DOCUMENTS_COMPANY_IDX ON DOCUMENTS (COMPANY, INPUT_DATE)';
    IF (NOT EXISTS(SELECT 1 FROM RDB$INDICES WHERE RDB$INDEX_NAME = 'IDX_DOC_COMPANY_PERIOD')) THEN
        EXECUTE STATEMENT 'CREATE INDEX IDX_DOC_COMPANY_PERIOD ON DOCUMENTS (COMPANY, PERIOD)';

    /* ---- PERIODS ---- */
    IF (NOT EXISTS(SELECT 1 FROM RDB$INDICES WHERE RDB$INDEX_NAME = 'IDX_PERIODS_COMPANY_DATES')) THEN
        EXECUTE STATEMENT 'CREATE INDEX IDX_PERIODS_COMPANY_DATES ON PERIODS (COMPANY, BEGINNING_DATE, ENDING_DATE)';
END ^

SET TERM ; ^

COMMIT;

/* Cap nhat thong ke chon loc index (giup optimizer dung index moi hieu qua) */
SET STATISTICS INDEX IDX_BAL_COMPANY_PERIOD;
SET STATISTICS INDEX IDX_BAL_PERIOD_ACC;
SET STATISTICS INDEX IDX_BAL_PERIOD_ACC_OBJ0;
SET STATISTICS INDEX IDX_CD_COMPANY_ACC_OBJ0;
SET STATISTICS INDEX IDX_CD_COMPANY_ACC_SIDE;
SET STATISTICS INDEX IDX_CD_ENTRY_ACC_OBJ0;
SET STATISTICS INDEX IDX_CD_ENTRY_ACC_SIDE;
SET STATISTICS INDEX DOCUMENTS_COMPANY_IDX;
SET STATISTICS INDEX IDX_DOC_COMPANY_PERIOD;
SET STATISTICS INDEX IDX_PERIODS_COMPANY_DATES;

COMMIT;
