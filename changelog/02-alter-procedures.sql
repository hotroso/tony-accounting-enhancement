ALTER PROCEDURE INT_PS_1_TK (P_COMPANY BIGINT,
P_ACCOUNT BIGINT,
P_TU_NGAY DATE,
P_DEN_NGAY DATE)
RETURNS (DEBIT_AMOUNT DECIMAL(18, 4),
DEBIT DECIMAL(18, 4),
CREDIT_AMOUNT DECIMAL(18, 4),
CREDIT DECIMAL(18, 4))
AS 
BEGIN
    IF (NOT EXISTS(SELECT 1 FROM DOCUMENTS WHERE COMPANY = :P_COMPANY AND INPUT_DATE BETWEEN :P_TU_NGAY AND :P_DEN_NGAY)) THEN
    BEGIN
        DEBIT_AMOUNT = 0; DEBIT = 0; CREDIT_AMOUNT = 0; CREDIT = 0;
        SUSPEND;
    END
    ELSE
    BEGIN
        SELECT
            SUM(IIF(cd.SIDE=0, cd.AMOUNT, 0)),
            SUM(IIF(cd.SIDE=0, cd.OFFICIAL_SUM_OF_MONEY, 0)),
            SUM(IIF(cd.SIDE=1, cd.AMOUNT, 0)),
            SUM(IIF(cd.SIDE=1, cd.OFFICIAL_SUM_OF_MONEY, 0))
        FROM (
            SELECT e.ID AS ENTRY_ID
            FROM DOCUMENTS d
            JOIN ENTRIES e ON e.DOCUMENT = d.ID AND e.COMPANY = d.COMPANY
            WHERE d.COMPANY = :P_COMPANY AND d.INPUT_DATE BETWEEN :P_TU_NGAY AND :P_DEN_NGAY
        ) de
        JOIN CREDIT_DEBIT cd ON cd.ENTRY = de.ENTRY_ID
            AND cd.COMPANY = :P_COMPANY AND cd.ACCOUNT = :P_ACCOUNT
        INTO :DEBIT_AMOUNT, :DEBIT, :CREDIT_AMOUNT, :CREDIT;

        IF (DEBIT IS NULL)        THEN DEBIT = 0;
        IF (DEBIT_AMOUNT IS NULL) THEN DEBIT_AMOUNT = 0;
        IF (CREDIT IS NULL)       THEN CREDIT = 0;
        IF (CREDIT_AMOUNT IS NULL) THEN CREDIT_AMOUNT = 0;

        SUSPEND;
    END
END ^

