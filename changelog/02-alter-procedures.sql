ALTER PROCEDURE INT_SD_1_TK_DN (P_COMPANY BIGINT,
P_ACCOUNT BIGINT,
P_NGAY DATE)
RETURNS (AMOUNT NUMERIC(18, 4),
DEBIT NUMERIC(18, 4),
CREDIT NUMERIC(18, 4))
AS 
DECLARE VARIABLE PERIOD BIGINT;
DECLARE VARIABLE BEGINNING_DATE DATE;
DECLARE VARIABLE BEGINNING_AMOUNT DOUBLE PRECISION;
DECLARE VARIABLE BEGINNING_DEBIT DOUBLE PRECISION;
DECLARE VARIABLE BEGINNING_CREDIT DOUBLE PRECISION;
DECLARE VARIABLE RISING_DEBIT_AMOUNT DOUBLE PRECISION;
DECLARE VARIABLE RISING_DEBIT DOUBLE PRECISION;
DECLARE VARIABLE RISING_CREDIT_AMOUNT DOUBLE PRECISION;
DECLARE VARIABLE RISING_CREDIT DOUBLE PRECISION;
BEGIN
    SELECT p.ID, p.BEGINNING_DATE
    FROM PERIODS p
    WHERE p.COMPANY = :P_COMPANY
      AND :P_NGAY BETWEEN p.BEGINNING_DATE AND p.ENDING_DATE
    INTO :PERIOD, :BEGINNING_DATE;

    SELECT SUM(b.AMOUNT), SUM(b.OFFICIAL_DEBIT), SUM(b.OFFICIAL_CREDIT)
    FROM BALANCES b
    WHERE b.PERIOD = :PERIOD AND b.ACCOUNT = :P_ACCOUNT
    PLAN (B INDEX (IDX_BAL_PERIOD_ACC))
    INTO :BEGINNING_AMOUNT, :BEGINNING_DEBIT, :BEGINNING_CREDIT;

    IF (BEGINNING_AMOUNT IS NULL) THEN BEGINNING_AMOUNT = 0;
    IF (BEGINNING_DEBIT IS NULL)  THEN BEGINNING_DEBIT = 0;
    IF (BEGINNING_CREDIT IS NULL) THEN BEGINNING_CREDIT = 0;

    IF (BEGINNING_DATE <> P_NGAY) THEN
    BEGIN
        SELECT DEBIT_AMOUNT, DEBIT, CREDIT_AMOUNT, CREDIT
        FROM INT_PS_1_TK(:P_COMPANY, :P_ACCOUNT, :BEGINNING_DATE, DATEADD(DAY, -1, :P_NGAY))
        INTO :RISING_DEBIT_AMOUNT, :RISING_DEBIT, :RISING_CREDIT_AMOUNT, :RISING_CREDIT;
    END

    IF (RISING_DEBIT_AMOUNT IS NULL)  THEN RISING_DEBIT_AMOUNT = 0;
    IF (RISING_DEBIT IS NULL)         THEN RISING_DEBIT = 0;
    IF (RISING_CREDIT_AMOUNT IS NULL) THEN RISING_CREDIT_AMOUNT = 0;
    IF (RISING_CREDIT IS NULL)        THEN RISING_CREDIT = 0;

    AMOUNT = BEGINNING_AMOUNT + RISING_DEBIT_AMOUNT - RISING_CREDIT_AMOUNT;
    DEBIT  = BEGINNING_DEBIT + RISING_DEBIT - BEGINNING_CREDIT - RISING_CREDIT;

    IF (DEBIT > 0) THEN
        CREDIT = 0;
    ELSE BEGIN
        CREDIT = ABS(DEBIT);
        DEBIT = 0;
    END

    SUSPEND;
END ^

ALTER PROCEDURE INT_SD_1_TK_DT0_DN (P_COMPANY BIGINT,
P_ACCOUNT BIGINT,
P_IS_GOODS_ACCOUNT SMALLINT,
P_NGAY DATE)
RETURNS (OBJECT0 BIGINT,
AMOUNT NUMERIC(18, 4),
DEBIT NUMERIC(18, 4),
CREDIT NUMERIC(18, 4))
AS 
DECLARE VARIABLE PERIOD BIGINT;
DECLARE VARIABLE BEGINNING_DATE DATE;
BEGIN
    SELECT p.ID, p.BEGINNING_DATE
    FROM PERIODS p
    WHERE p.COMPANY = :P_COMPANY
      AND :P_NGAY BETWEEN p.BEGINNING_DATE AND p.ENDING_DATE
    INTO :PERIOD, :BEGINNING_DATE;

    IF (BEGINNING_DATE = P_NGAY) THEN
    BEGIN
        FOR
            SELECT b.OBJECT0, SUM(b.AMOUNT), SUM(b.OFFICIAL_DEBIT), SUM(b.OFFICIAL_CREDIT)
            FROM BALANCES b
            WHERE b.PERIOD = :PERIOD
              AND b.ACCOUNT = :P_ACCOUNT AND b.OBJECT0 IS NOT NULL
            GROUP BY b.OBJECT0
            PLAN (B INDEX (IDX_BAL_PERIOD_ACC))
            INTO :OBJECT0, :AMOUNT, :DEBIT, :CREDIT
        DO BEGIN
            DEBIT = DEBIT - CREDIT;
            IF (DEBIT > 0) THEN CREDIT = 0;
            ELSE BEGIN CREDIT = ABS(DEBIT); DEBIT = 0; END
            IF (DEBIT <> 0 OR CREDIT <> 0 OR (P_IS_GOODS_ACCOUNT = 1 AND AMOUNT <> 0)) THEN
                SUSPEND;
        END
    END
    ELSE
    BEGIN
        FOR
            SELECT OBJECT0, SUM(AMOUNT), SUM(DEBIT), SUM(CREDIT)
            FROM (
                SELECT b.OBJECT0, b.AMOUNT, b.OFFICIAL_DEBIT DEBIT, b.OFFICIAL_CREDIT CREDIT
                FROM BALANCES b
                WHERE b.PERIOD = :PERIOD
                  AND b.ACCOUNT = :P_ACCOUNT AND b.OBJECT0 IS NOT NULL
                UNION ALL
                SELECT OBJECT0, DEBIT_AMOUNT - CREDIT_AMOUNT, DEBIT, CREDIT
                FROM INT_PS_1_TK_DT0(:P_COMPANY, :P_ACCOUNT, :BEGINNING_DATE, DATEADD(DAY, -1, :P_NGAY))
            )
            GROUP BY OBJECT0
            INTO :OBJECT0, :AMOUNT, :DEBIT, :CREDIT
        DO BEGIN
            DEBIT = DEBIT - CREDIT;
            IF (DEBIT > 0) THEN CREDIT = 0;
            ELSE BEGIN CREDIT = ABS(DEBIT); DEBIT = 0; END
            IF (DEBIT <> 0 OR CREDIT <> 0 OR (P_IS_GOODS_ACCOUNT = 1 AND AMOUNT <> 0)) THEN
                SUSPEND;
        END
    END
END ^

